        <h2>Come funziona il portale</h2>
        <p>Passo Verde raccoglie escursioni di diversa difficoltà. Puoi consultarle liberamente, cercare per nome o località e confrontare lunghezza, durata e dislivello.</p>
        <p>Con un account puoi salvare i percorsi tra i preferiti, pubblicare una recensione e aggiornarla o cancellarla. L’amministratore cura il catalogo e modera i contributi.</p>
        <p>Questo è un sito di prova per Tecnologie Web: località, itinerari e dati sono inventati. Le fotografie sono illustrative e non identificano i percorsi descritti.</p>
    </section>
</div>
<section class="reading section" id="difficolta">
    <h2>Come leggere le difficoltà</h2>
    <p>Le tre etichette servono a provare la ricerca nel catalogo dimostrativo. Non sono una classificazione tecnica ufficiale dei sentieri.</p>
    <dl class="difficulty-list">
        <dt>Facile</dt>
        <dd>Percorsi del catalogo più brevi e con dislivello contenuto.</dd>
        <dt>Media</dt>
        <dd>Escursioni del catalogo con durata e salita intermedie.</dd>
        <dt>Difficile</dt>
        <dd>Itinerari del catalogo più lunghi e con dislivello maggiore.</dd>
    </dl>
    <p>Questo prototipo non fornisce tracce o informazioni utilizzabili per organizzare escursioni reali.</p>
</section>
